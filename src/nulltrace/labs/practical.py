@dataclass(frozen=True)
class LabResult:
    success: bool
    mode: str                 # real | simulated | unavailable
    title: str
    details: tuple[str, ...]
    evidence: str = ''


def packet_file_sanity(path: Path = PCAP) -> dict:
    """Minimal bundled-PCAP format check; does not parse arbitrary network capture."""
    raw = path.read_bytes()
    if len(raw) < 40 or raw[:4] != b'\xd4\xc3\xb2\xa1':
        raise ValueError('The bundled little-endian PCAP fixture is invalid')
    offset, frames = 24, 0
    while offset<len(raw):
        if offset + 16 > len(raw):raise ValueError('Partial packet header')
        ts, frac, captured, original = struct.unpack_from('<IIII',raw,offset)
        if captured > 65535 or original < captured or offset + 16 + captured > len(raw):
            raise ValueError('Invalid frame bounds')
        frames += 1;offset += 16 + captured
    if offset != len(raw) or frames < 2:raise ValueError('Invalid PCAP fixture')
    return {'frames': frames, 'sha256': hashlib.sha256(raw).hexdigest()}


def packet_lab() -> LabResult:
    """Pipe the trusted PCAP to TShark; no path-based read permission required.

    Ubuntu AppArmor confinement can deny TShark direct access to user-owned
    Documents directories even when Python can read the file. Classic PCAP
    is stream-readable, so `-r -` avoids weakening system security profiles.
    """
    try:
        metadata = packet_file_sanity()
        raw = PCAP.read_bytes()
        if len(raw) > 2_000_000:
            raise ValueError('Unexpectedly large bundled packet fixture')
    except (OSError, ValueError) as exc:
        return LabResult(False, 'unavailable', 'Packet archive', (str(exc),))
    tshark = shutil.which('tshark')
    if tshark:
        command = [tshark, '-n', '-r', '-', '-Y', 'dns', '-T', 'fields',
                   '-e', 'ip.src', '-e', 'ip.dst', '-e', 'dns.qry.name']
        try:
            proc = subprocess.run(command, input=raw, capture_output=True,
                                  timeout=12, check=False)
            if proc.returncode == 0:
                lines = [line.strip() for line in proc.stdout.decode('utf-8', errors='replace').splitlines() if line.strip()]
                valid = any(TRAINING_DOMAIN in line and '192.0.2.10' in line for line in lines)
                if valid:
                    return LabResult(True, 'real', 'TShark offline packet inspection',
                        tuple([f'Frames: {metadata["frames"]}', 'Trusted capture piped via stdin (no live sniffing):'] +
                              lines[:10] + [f'Fixture SHA-256: {metadata["sha256"][:16]}…']),
                        f'packet:{metadata["sha256"][:16]}')
                failure = 'TShark returned no matching DNS observations.'
            else:
                failure = (proc.stderr.decode('utf-8', errors='replace') or 'TShark failed')[:240].strip()
        except (subprocess.TimeoutExpired, OSError) as exc:
            failure = f'TShark error: {exc}'
    else:
        failure = 'TShark is not installed.'
    return LabResult(True, 'simulated', 'Bundled packet review', (
        f'{failure} Using the fixed, synthetic fixture briefing instead.',
        f'Frames: {metadata["frames"]}',
        f'Workstation 192.0.2.10 queries {TRAINING_DOMAIN}',
        'DNS server: 198.51.100.53 (documentation address)',
        'No network traffic was captured or generated by this exercise.',
    ), f'packet:simulation:{metadata["sha256"][:16]}')


def parse_nmap_xml(xml: str, wanted_port: int) -> str:
    """Only handle bounded XML returned by our 127.0.0.1 scan."""
    if len(xml)>300_000:raise ValueError('Oversized scan output')
    root=ET.fromstring(xml)
    for host in root.findall('host'):
        if not any(a.get('addr')=='127.0.0.1' for a in host.findall('address') + host.findall('addresses/address')):continue
        for port in host.findall('ports/port'):
            if port.get('portid') == str(wanted_port) and port.get('protocol')=='tcp':
                state=port.find('state')
                if state is not None:return state.get('state','unknown')
    return 'not-found'


def nmap_lab() -> LabResult:
    binary = shutil.which('nmap')
    if not binary:
        return LabResult(True,'simulated','Nmap introduction',(
            'Nmap is not installed; viewing a safe simulated report.',
            'Host 127.0.0.1 / TCP 8000 / state open (FICTIONAL)',
            'Actual scans are enabled only when nmap is installed.',
        ),'nmap:simulation')
    listener = socket.socket(socket.AF_INET,socket.SOCK_STREAM)
    listener.setsockopt(socket.SOL_SOCKET,socket.SO_REUSEADDR,1)
    try:
        listener.bind(('127.0.0.1',0))
        listener.listen(3)
        port=listener.getsockname()[1]
        # All arguments are constructed internally. No user-supplied targets or flags.
        cmd=[binary,'-sT','-Pn','-p',str(port),'-oX','-','127.0.0.1']
        try:
            proc=subprocess.run(cmd,capture_output=True,text=True,timeout=18,check=False)
        except (OSError,subprocess.TimeoutExpired) as exc:
            return LabResult(False,'unavailable','Loopback Nmap exercise',(f'Scan did not finish: {exc}',))
        if proc.returncode != 0:
            return LabResult(False,'unavailable','Loopback Nmap exercise',((proc.stderr or 'Nmap returned a failure')[:220],))
        try:state=parse_nmap_xml(proc.stdout,port)
        except (ET.ParseError,ValueError) as exc:return LabResult(False,'unavailable','Loopback Nmap exercise',(f'Invalid Nmap output: {exc}',))
        return LabResult(state=='open','real','Nmap local-only scan',(
            f'Authorized target: 127.0.0.1', f'Temporary controlled TCP port: {port}',
            f'Nmap reported: {state}', 'This result proves only that a local TCP listener was reachable.'
        ),f'nmap:127.0.0.1:{port}:{state}')
    finally:listener.close()


def john_lab() -> LabResult:
    """Offline wordlist lab compatible with basic John and jumbo editions.

    Basic John accepts --format, --wordlist and --show, but not --pot. Keep
    its HOME, XDG data, and working directory inside a temporary directory.
    """
    binary = shutil.which('john')
    openssl = shutil.which('openssl')
    if binary and openssl:
        with tempfile.TemporaryDirectory(prefix='nulltrace_john_') as directory:
            tmp = Path(directory)
            prep = subprocess.run([openssl, 'passwd', '-1', '-salt', 'ntlab', TEST_PASSWORD],
                                  capture_output=True, text=True, timeout=8, check=False)
            if prep.returncode == 0 and prep.stdout.strip().startswith('$1$'):
                hashfile = tmp / 'synthetic.hash'
                wordfile = tmp / 'wordlist.txt'
                hashfile.write_text('training:' + prep.stdout.strip() + '\n', encoding='utf-8')
                wordfile.write_text('\n'.join(WORDS) + '\n', encoding='utf-8')
                (tmp / '.john').mkdir(mode=0o700)
                clean_env = os.environ.copy()
                clean_env.update({'HOME': str(tmp), 'XDG_CONFIG_HOME': str(tmp),
                                  'XDG_DATA_HOME': str(tmp)})
                # John's basic/Core builds reject --pot and --help; both
                # versions accept --wordlist, --format and --show.
                cmd = [binary, '--format=md5crypt', f'--wordlist={wordfile}', str(hashfile)]
                try:
                    ran = subprocess.run(cmd, capture_output=True, text=True, timeout=18,
                                         check=False, cwd=tmp, env=clean_env)
                    shown = subprocess.run([binary, '--show', '--format=md5crypt', str(hashfile)],
                                           capture_output=True, text=True, timeout=8,
                                           check=False, cwd=tmp, env=clean_env)
                    if shown.returncode == 0 and 'training:' + TEST_PASSWORD in shown.stdout:
                        return LabResult(True, 'real', 'John: synthetic credential audit', (
                            'Fixture: generated MD5-crypt hash for training only (not modern password storage).',
                            'The five-word local training dictionary identified the deliberately weak test credential.',
                            'John worked with its isolated temporary home; no personal credentials were accessed.',
                            'Modern systems should use suitable adaptive password hashing plus MFA.',
                        ), 'john:synthetic-weak-credential')
                    failure = (ran.stderr or shown.stderr or ran.stdout or
                               'John could not load or show the training hash')[:240].strip()
                except (OSError, subprocess.TimeoutExpired) as exc:
                    failure = f'John did not complete: {exc}'
            else:
                failure = 'OpenSSL could not generate the synthetic training hash.'
    else:
        failure = 'John and/or OpenSSL not installed.'
    salt = b'nulltrace-demo-salt'
    expected = hashlib.pbkdf2_hmac('sha256', TEST_PASSWORD.encode(), salt, 2000)
    found = next((w for w in WORDS if hashlib.pbkdf2_hmac('sha256', w.encode(), salt, 2000) == expected), None)
    return LabResult(bool(found), 'simulated', 'Synthetic password-audit simulation', (
        f'{failure} Running explicit built-in training simulation instead.',
        f'Synthetic credential matched a word in the tiny wordlist: {bool(found)}',
        'Modern password-storage systems should use suitably configured adaptive hashing.',
        'No real credentials were accessed.',
    ), 'john:simulation')


def web_lab() -> LabResult:
    """Check manual localhost HTTP lab receipt; never claim Burp was verified."""
    from nulltrace.labs.web_training import receipt_status
    success, detail = receipt_status()
    return LabResult(success, 'local-http' if success else 'pending',
        'Behind the Browser / local HTTP', (
            detail,
            'Run python -m nulltrace --web-lab in another terminal, then use Burp Community Repeater.',
            'This synthetic portal deliberately lacks object-level authorization. No real accounts exist.',
        ), 'web:loopback-receipt' if success else '')


def incident_lab() -> LabResult:
    """Inspect the bundled evidence chain without accessing a network."""
    from nulltrace.labs.incident import inspect_case
    try:
        report=inspect_case()
    except (OSError,ValueError,KeyError,TypeError) as exc:
        return LabResult(False,'unavailable','Synthetic NEXUS incident review',(str(exc),))
    return LabResult(True,'offline','Synthetic NEXUS incident review',(
        f'Verified synthetic timeline events: {report["events"]}',
        f'SHA-256: {report["sha256"][:24]}…', report['discrepancy'],
        report['qualification'], 'The dossier is fictional and never proves a real-world allegation.',
    ),f'incident:{report["sha256"][:16]}')

